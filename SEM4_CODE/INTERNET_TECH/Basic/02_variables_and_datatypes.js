let studentName = "Sujit";                                                    // String
const rollNumber = 101;                                                       // Number (Integer)
let marks = 89.5;                                                             // Number (Float)
let isPassed = true;                                                          // Boolean
let subjectGrade = null;                                                      // Null
let pendingSubmission;                                                        // Undefined
let bigIntegerVal = 9007199254740991n;                                        // BigInt
console.log("studentName    :", studentName, "| Type:", typeof studentName);  // Demonstrates var, let, const, and typeof operator
console.log("rollNumber     :", rollNumber, " | Type:", typeof rollNumber);
console.log("marks          :", marks, " | Type:", typeof marks);
console.log("isPassed       :", isPassed, "  | Type:", typeof isPassed);
console.log("subjectGrade   :", subjectGrade, "  | Type:", typeof subjectGrade);
console.log("pendingSubmit  :", pendingSubmission, " | Type:", typeof pendingSubmission);
console.log("bigIntegerVal  :", bigIntegerVal, "| Type:", typeof bigIntegerVal);
