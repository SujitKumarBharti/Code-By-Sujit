n = 5                                         # Perform calculation
for i in range(1, n + 1):                     # Iterate through loop
    print(" " * (n - i) + "*" * (2 * i - 1))  # Display print a diamond star pattern result
for i in range(n - 1, 0, -1):                 # Iterate through loop
    print(" " * (n - i) + "*" * (2 * i - 1))  # Display print a diamond star pattern result
