numbers = [10, 20, 30]               # Create a list of numbers
print("Original list:", numbers)     # Display the list

numbers.append(40)                   # Add an item to the list
print("After append:", numbers)      # Display the updated list

numbers.remove(20)                   # Remove an item from the list
print("After remove:", numbers)      # Display the updated list

print("First item:", numbers[0])     # Display the first item
print("List length:", len(numbers))  # Display the number of items
