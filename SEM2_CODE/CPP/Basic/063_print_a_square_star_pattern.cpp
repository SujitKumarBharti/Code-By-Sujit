#include <iostream>
using namespace std;

int main() {
    int size = 5;                                      // Initialize variable
    for (int i = 1; i <= size; i++) {                  // Iterate through loop
        for (int j = 1; j <= size; j++) cout << "* ";  // Display print a square star pattern result
        cout << endl;                                  // Display print a square star pattern result
    }
    return 0;                                          // Exit program successfully
}
