#include <stdio.h>

int main(void) {
    int size = 5;                            // Initialize variable
    for (int i = 1; i <= size; i++) {        // Iterate through loop
        for (int j = 1; j <= size; j++) {    // Iterate through loop
            printf("* ");                    // Display print a square star pattern result
        }
        printf("\n");                        // Display print a square star pattern result
    }
    return 0;                                // Exit program successfully
}
