#include <stdio.h>

int main(void) {
    for (int i = 2; i <= 100; i += 2) {      // Iterate through loop
        printf("%d ", i);                    // Display print all even numbers from 1 to... result
    }
    printf("\n");                            // Display print all even numbers from 1 to... result
    return 0;                                // Exit program successfully
}
