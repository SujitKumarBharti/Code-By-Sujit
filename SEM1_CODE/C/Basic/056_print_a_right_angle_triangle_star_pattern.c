#include <stdio.h>

int main(void) {
    int rows = 5;                            // Initialize variable
    for (int i = 1; i <= rows; i++) {        // Iterate through loop
        for (int j = 1; j <= i; j++) {       // Iterate through loop
            printf("* ");                    // Display print a right-angle triangle sta... result
        }
        printf("\n");                        // Display print a right-angle triangle sta... result
    }
    return 0;                                // Exit program successfully
}
