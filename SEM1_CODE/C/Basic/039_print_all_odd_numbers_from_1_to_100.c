#include <stdio.h>

int main(void) {
    for (int i = 1; i <= 100; i += 2) {      // Iterate through loop
        printf("%d ", i);                    // Display print all odd numbers from 1 to 100 result
    }
    printf("\n");                            // Display print all odd numbers from 1 to 100 result
    return 0;                                // Exit program successfully
}
