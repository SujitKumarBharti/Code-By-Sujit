#include <stdio.h>

int main(void) {
    for (int i = 100; i >= 1; i--) {         // Iterate through loop
        printf("%d ", i);                    // Display print numbers from 100 to 1 result
    }
    printf("\n");                            // Display print numbers from 100 to 1 result
    return 0;                                // Exit program successfully
}
