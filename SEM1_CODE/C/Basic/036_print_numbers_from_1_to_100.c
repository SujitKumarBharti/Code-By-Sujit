#include <stdio.h>

int main(void) {
    for (int i = 1; i <= 100; i++) {         // Iterate through loop
        printf("%d ", i);                    // Display print numbers from 1 to 100 result
    }
    printf("\n");                            // Display print numbers from 1 to 100 result
    return 0;                                // Exit program successfully
}
