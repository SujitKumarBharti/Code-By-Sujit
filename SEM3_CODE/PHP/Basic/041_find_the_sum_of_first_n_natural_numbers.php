<?php
$n = (int) readline("Enter N: ");                        // Prompt user for input
$sum = 0;                                                // Store variable value
for ($i = 1; $i <= $n; $i++) {                           // Iterate through loop
    $sum += $i;                                          // Store variable value
}
echo "Sum of first $n natural numbers: $sum" . PHP_EOL;  // Display find the sum of first N natural ... result
?>
