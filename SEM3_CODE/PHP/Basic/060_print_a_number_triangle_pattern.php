<?php
$rows = 5;                                   // Store variable value
for ($i = 1; $i <= $rows; $i++) {            // Iterate through loop
    for ($j = 1; $j <= $i; $j++) {           // Iterate through loop
        echo "$j ";                          // Display print a number triangle pattern result
    }
    echo PHP_EOL;                            // Display print a number triangle pattern result
}
?>
