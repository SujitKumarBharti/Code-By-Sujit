<?php
$size = 5;                                   // Store variable value
for ($i = 1; $i <= $size; $i++) {            // Iterate through loop
    for ($j = 1; $j <= $size; $j++) {        // Iterate through loop
        echo "* ";                           // Display print a square star pattern result
    }
    echo PHP_EOL;                            // Display print a square star pattern result
}
?>
