class Q039_OddNumbers1To100 {
    public static void main(String[] args) {
        for (int i = 1; i <= 100; i += 2) System.out.print(i + " ");  // Display print all odd numbers from 1 to 100 result
        System.out.println();                                         // Display print all odd numbers from 1 to 100 result
    }
}
