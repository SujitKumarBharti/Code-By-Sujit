class Q063_SquareStar {
    public static void main(String[] args) {
        int size = 5;                                                // Initialize variable
        for (int i = 1; i <= size; i++) {                            // Iterate through loop
            for (int j = 1; j <= size; j++) System.out.print("* ");  // Display print a square star pattern result
            System.out.println();                                    // Display print a square star pattern result
        }
    }
}
