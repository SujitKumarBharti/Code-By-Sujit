class Q067_SumArrayElements {
    public static void main(String[] args) {
        int[] arr = {10, 20, 30, 40, 50};                     // Perform calculation
        int sum = 0;                                          // Initialize variable
        for (int x : arr) sum += x;                           // Iterate through loop
        System.out.println("Sum of array elements: " + sum);  // Display find the sum of array elements result
    }
}
