class Q056_RightAngleTriangle {
    public static void main(String[] args) {
        int rows = 5;                                             // Initialize variable
        for (int i = 1; i <= rows; i++) {                         // Iterate through loop
            for (int j = 1; j <= i; j++) System.out.print("* ");  // Display print a right-angle triangle sta... result
            System.out.println();                                 // Display print a right-angle triangle sta... result
        }
    }
}
